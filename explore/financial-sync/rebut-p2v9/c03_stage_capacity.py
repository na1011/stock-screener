# v9 결정 3(단계 우선 · 강제일만 무거운 잡 몫 예약)의 하루 단계 짝 상한 — 계획 자기 수로(짝 81 평균 · 73~108 · v6 반증) · 사슬 950 · 한도 18,000.
LIMIT, CHAIN = 18000, 950
HEAVY = {'없음/비강제': 0, 'G 강제': 8050, 'FR 강제': 12600, 'FSR 강제': 15844}
for k, h in HEAVY.items():
    room = LIMIT - CHAIN - h
    print(f'{k:>8}: 단계 예산 {room:6d}콜 → 짝 {room // 108:3d}~{room // 73:3d} (평균 81이면 {room // 81})')
print('비강제일에 무거운 잡이 같은 날 돌 수 있는 단계 상한(남은 예산 ≥ 몫): G ≤ %d짝 · FR ≤ %d짝 · FSR ≤ %d짝'
      % ((LIMIT - CHAIN - 8050) // 81, (LIMIT - CHAIN - 12600) // 81, (LIMIT - CHAIN - 15844) // 81))
print('「11-17 단계가 287짝을 다 받고」: 287 × 81 =', 287 * 81, '>', LIMIT - CHAIN, '→ 하루에 못 든다(평균 기준 이월', 287 - (LIMIT - CHAIN) // 81, '짝)')
