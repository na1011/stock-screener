package com.stockscreener.pipeline.datasource;

import java.util.Set;

/**
 * 우리가 <b>종목 데이터를 모으기로 한</b> 시장(ADR-0087).
 *
 * <p>유니버스에 편입하는 것과 데이터를 모으는 것은 다르다. 어댑터가 없는 시장의 종목을 배치
 * 대상에 넣으면 종목마다 {@code NOT_FOUND}로 실패해 <b>부분 실패 알림이 상시화되고 진짜 장애가
 * 묻힌다.</b> ADR-0010이 §버린 대안에서 명시적으로 기각한 상태이고, 미국의 규모가 8,504종목이다.
 * 게다가 {@code CorporateActionJob}처럼 루프 앞에서 시장별 소스를 먼저 해석하는 잡은
 * <b>국내 수집까지 통째로 멈춘다.</b>
 *
 * <p><b>어댑터 등록 여부와 무관한 목록이라는 것이 요점이다</b>({@code MarketIndexCodes}가 같은
 * 이유로 같은 형태다). 등록된 어댑터에서 뽑으면 키가 없는 테스트 환경에서 목록이 비어
 * <b>모든 잡의 대상이 0건</b>이 되고, 그것은 정상과 구분되지 않는다.
 *
 * <p>그래서 이 목록은 <b>선언</b>이다 — 시장을 여기 더하는 것이 "그 시장의 데이터를 모으기로
 * 했다"는 뜻이고, 어댑터가 실제로 없으면 그때는 실패가 나야 한다.
 *
 * <p><b>미국을 더하는 시점을 「시세와 재무」에서 「시세」로 앞당겼다(2026-08-29 사용자 결정,
 * ADR-0088).</b> 사용자가 고른 문장은 <i>"지금 더한다"</i>이고, 그에 대한 해석이 위 한 줄이다 —
 * 둘을 갈라 적는 이유는 다음 세션이 해석을 결정으로 읽지 않게 하려는 것이다.
 *
 * <p><b>선언이 앞당겨져도 없어지지 않는 것</b>: 미국에 <b>재무와 기업 행위는 붙었지만</b>
 * (ADR-0089·0090) 전체재무제표·기업개황·거버넌스 어댑터가 없다. 그 셋이 지금 미국을 대상으로
 * 삼지 않는 이유는 이 목록이 아니라 <b>{@code US_LISTED}가 비활성이라는 것</b>이다.
 * <b>배치를 통째로 죽이던 자리는 닫혔다</b> — {@code CorporateActionJob}이 루프 앞에서
 * {@code requireSources}로 소스를 해석하는 유일한 잡인데 이제 미국 소스를 찾는다. 남은 것은
 * <b>그 유니버스를 켜면 세 잡이 매 실행 8,504건 부분 실패를 남기는 것</b>이고, 그러면 진짜
 * 장애가 묻힌다. 켜기 전에 그 어댑터들이 있어야 한다 — ADR-0086의 premise가 무엇이 없는지를
 * 수로 답한다.
 *
 * <p>MUST NOT: 유니버스 편입을 이 목록으로 막지 않는다. 지나간 시점의 유니버스는 사후 복원이
 * 불가능하므로(생존편향), 데이터를 모으기 전에도 <b>구성은 쌓아 둔다.</b>
 */
public final class CollectedMarkets {

    /**
     * 시장 코드와 같은 문자열을 쓴다 — 종목의 {@code market_code}로 곧장 고를 수 있게.
     *
     * <p>이 목록의 사본이 ADR-0087의 premise SQL에 리터럴로 있다. <b>여기를 늘리면 그쪽도
     * 함께 고친다</b> — 안 고치면 의도한 동작에 우는 펜스가 된다.
     */
    public static final Set<String> ALL = Set.of("KOSPI", "KOSDAQ", "US");

    private CollectedMarkets() {
    }
}
