package com.stockscreener.screening;

/**
 * 조건 집합을 어떻게 판정할 것인가.
 *
 * <p>같은 {@link ConditionGroup}이 두 방식 모두로 실행될 수 있다. 판정 방식은 조건의 속성이
 * 아니라 실행의 속성이므로, 프리셋을 필터로 돌리거나 사용자 화면에 가중치를 주는 것이 공짜다.
 */
public enum EvaluationMode {

    /**
     * 충족/불충족으로 걸러낸다. 조건을 모두 만족하는 종목만 남는다.
     *
     * <p>판정 불가(지표 없음)는 통과시키지 않는다.
     */
    FILTER,

    /**
     * 가중치 합으로 점수를 매긴다. 좁히는 조건이 없으므로 <b>모든 종목이 결과에 남고</b>
     * 점수 순으로 정렬된다.
     *
     * <p>일부 조건만 만족한 종목도 그만큼의 점수를 갖고 남아야 한다 — 그것이 프리셋 전략이
     * 순위를 매기는 방식이다.
     */
    SCORING
}
