package com.stockscreener.indicator;

/**
 * 거버넌스 원자료에서 유도한 <b>숫자 하나</b>의 이름. {@code governance_fact.metric_key}의 값이다.
 *
 * <p>IMPORTANT — <b>지표 코드가 아니다.</b> 여기 있는 것은 「소스가 준 수」이고, 지표는 그것들을
 * 조합해 계산기가 만든다. 둘을 같은 이름으로 부르면 종가로 나누는 {@code DIVIDEND_YIELD}가
 * <b>회계연도당 하나로 저장되는 물건</b>이 되는데, 그 값은 날마다 달라지므로 틀린 저장이다.
 *
 * <p>MUST NOT: 값을 빼거나 이름을 바꾸지 않는다({@link IndicatorCategory}와 같은 형태의 금지다).
 * {@code governance_fact}에 CHECK가 없고 리더가 모르는 키를 <b>던지지 않고 건너뛰므로</b>,
 * 이름을 바꾸면 <b>컴파일도 테스트도 초록인 채</b> 그 지표만 전 종목 판정불가가 된다. 게다가
 * {@code IndicatorUnavailabilityConfig}에 등록된 사유가 그대로 화면에 나가 <b>거짓 이유</b>를
 * 말한다. 더하는 것은 안전하고 빼는 것은 안전하지 않다.
 *
 * <p><b>단위와 주식 종류를 상수마다 못박는다.</b> 소스가 단위를 필드로 주지 않고 항목명 문자열
 * 안에만 넣기 때문이다 — {@code 현금배당금총액(백만원)}과 {@code 주당 현금배당금(원)}이 같은
 * 응답에 함께 온다(§16-C).
 */
public enum GovernanceMetric {

    /**
     * Ⅳ. 발행주식의 총수, <b>보통주 행</b>. 단위 주.
     *
     * <p>Ⅱ({@code now_to_isu_stock_totqy}, 발행 누계)와 다른 값이다. 그리고 {@code 합계} 행을
     * 쓰면 우선주가 섞여 <b>{@code price_daily.listed_shares} 기반 기존 지표와 분모가 갈린다</b>
     * (삼성전자 합계 67.4억 대 보통주 59.2억, §16-A).
     */
    ISSUED_SHARES_COMMON,

    /** Ⅴ. 자기주식수, <b>보통주 행</b>. 단위 주. */
    TREASURY_SHARES_COMMON,

    /**
     * Ⅲ의 내역 중 이익소각, <b>보통주 행</b>. 단위 주.
     *
     * <p>IMPORTANT — <b>상장 이래 누적이다.</b> 그대로 한 해치로 읽으면 상장 이래 전량이 그 해에
     * 소각된 것으로 나온다. 쓰는 쪽이 <b>두 회계연도의 차분</b>을 낸다.
     *
     * <p>{@code redc}(감자)를 여기 합치지 않는다 — <b>무상감자는 주주환원이 아니라 결손보전</b>이고,
     * 주식병합형이면 발행주식수를 크게 줄여 소각 기업과 부실 기업이 같은 칸에 앉는다.
     */
    PROFIT_RETIRED_CUM,

    /**
     * 주당 현금배당금, <b>보통주</b>. 단위 <b>원</b>.
     *
     * <p>소스의 {@code se}가 {@code 주당 현금배당금(원)}이고 {@code stock_knd}가 {@code 보통주}인
     * 행이다. 주식 종류 어휘가 넷이라({@code 보통주}·{@code 우선주}·{@code 종류주}·{@code -})
     * 「우선주가 아니면 보통주」로 접으면 틀린다(§16-C).
     */
    DPS_COMMON,

    /**
     * 현금배당 총액. 단위 <b>원</b>.
     *
     * <p>IMPORTANT — 소스는 <b>백만원</b>으로 준다({@code 현금배당금총액(백만원)}). 유도 단계에서
     * 10^6을 곱해 <b>원으로 정규화한 값</b>이 여기 담긴다 — {@code financial_statement.net_income}이
     * 원이므로, 안 맞추면 배당성향이 100만분의 1이 되고 <b>값이 작아 눈에 덜 띈다.</b>
     */
    CASH_DIVIDEND_TOTAL,

    /** 이사·감사 전체의 보수 지급 총액. 단위 원. */
    EXEC_PAY_TOTAL,

    /** 이사의 수. 단위 명. */
    DIRECTOR_COUNT,

    /** 독립(사외)이사의 수. 단위 명. */
    OUTSIDE_DIRECTOR_COUNT,

    /**
     * 사외이사 해임 수. 단위 명.
     *
     * <p>소스의 {@code -}는 <b>0명</b>이다 — 표본 여덟에서 해임이 8/8, 중도퇴임이 6/8로 {@code -}인데
     * 이사 수는 다 채워져 있다(§16-C). 결손으로 세면 이사회 축이 전 종목 판정불가가 된다.
     */
    DIRECTOR_DISMISSED,

    /** 사외이사 중도퇴임 수. 단위 명. {@code -}는 0명이다. */
    DIRECTOR_RESIGNED,

    /**
     * 최대주주와 특수관계인의 기말 소유 주식 수, <b>보통주 축</b>. 단위 주.
     *
     * <p>{@code nm}이 {@code 계}인 <b>합계 행을 빼고</b> 나머지를 더한 값이다. 안 빼면 정확히
     * 두 배가 된다. 판정은 <b>완전일치</b>로 한다 — {@code contains("계")}는 {@code 계열회사}·
     * {@code 특수관계인}을 함께 문다(실제로 물었다).
     */
    LARGEST_HOLDER_SHARES_COMMON,

    /** 소액주주 보유 주식 수. 단위 주. 분모와 <b>같은 행</b>에서 온다. */
    MINORITY_SHARES,

    /**
     * 소액주주 현황이 준 총발행주식수. 단위 주.
     *
     * <p>{@link #ISSUED_SHARES_COMMON}과 <b>따로 두는 이유</b>는 분자와 짝이 맞는 분모를 같은
     * 행에서 가져오기 위해서다. 다른 표의 수로 나누면 기준일이 갈리는데 값은 그럴듯하다.
     * 실측에서 이 값은 보통주 축이었다(삼성전자 5,919,637,922, §16-C).
     */
    MINORITY_TOTAL_SHARES,

    /**
     * 그 보고서 기준 <b>최근 3개 회계연도에 최대주주가 바뀐 횟수</b>. 단위 건.
     *
     * <p>IMPORTANT — 응답의 <b>행 수가 아니다.</b> 그 표는 최대주주의 <b>지분 변동 내역</b>이라
     * KB금융의 28행이 전부 같은 {@code 국민연금공단}이고 원인이 전부 {@code 장내매매}였다(§16-C).
     * 행 수를 세면 「자주 바뀌는 회사」와 「연기금이 매 분기 조금씩 사고파는 회사」가 같아진다.
     * 세는 것은 {@code mxmm_shrholdr_nm}이 <b>바뀐 전이</b>다.
     *
     * <p><b>창을 유도가 자른다.</b> 원자료가 요청 연도까지의 누적이라 보고서 하나가 창 전체를
     * 알고 있기 때문이다. 회계연도별로 쪼개 담지 않는 이유는 <b>사건이 없는 해에 0을 적을지</b>가
     * 갈리기 때문이다 — 적으면 상장 전 해에도 「변동 없음」이라 말하게 되고, 안 적으면 3년 합이
     * 조용히 부분 합이 된다. 창을 여기서 닫으면 그 갈림 자체가 없다.
     */
    CONTROL_TRANSFERS_3Y,

    /**
     * <b>강조사항</b>이 있으면 1, 없으면 0.
     *
     * <p>판정은 <b>「없음」 쪽 허용목록</b>으로 한다. 그 밖은 강조사항의 <b>내용 자체</b>라
     * 「모르는 토큰」이 아니다 — {@code adt_opinion}과 성격이 다른 이유가 이것이고, 그래서 목록 밖을
     * 판정불가가 아니라 1로 떨어뜨려도 <b>위험이 안전 쪽으로 새지 않는다.</b>
     *
     * <p>MUST NOT: <b>핵심감사사항을 여기 세지 않는다.</b> 감사기준의 필수 기재사항이라 표본
     * 48행이 전부 값을 갖는다(§16-C) — 세면 이 지표가 전 종목 1인 상수가 된다. 강조사항은
     * 41/48이 「없음」이라 실제로 가른다.
     *
     * <p>한 회계연도에 행이 둘이라(연결·별도로 보이나 필드로 구분되지 않는다) <b>OR로 접는다.</b>
     */
    AUDIT_EMPHASIS_PRESENT,

    /**
     * 그 회계연도의 감사의견이 <b>비적정</b>이면 1, 적정이면 0. <b>모르는 표기면 값을 내지 않는다.</b>
     *
     * <p>이 상수가 존재하는 근거는 실측이다. §10-D·§16-B가 <i>"활성 유니버스 안에서는 원리적으로
     * 안 나온다"</i>고 적었으나 <b>350종목 × 6개년 적재가 그것을 뒤집었다</b> — 044490 태웅의
     * FY2020이 {@code 감사범위 제한으로 인한 한정}이다(§16-C). 표본 여덟으로는 원리적으로 못 보던 것이다.
     *
     * <p>MUST: 판정은 <b>관측된 문자열의 완전일치 허용목록</b>이다. {@code contains("적정")}으로
     * 물으면 <b>{@code 부적정의견}이 「적정」으로 분류된다</b> — 한 글자가 가장 위험한 종목을
     * 통과시킨다. 목록 밖은 <b>판정불가 + 로그</b>이며 그것이 새 표기가 드러나는 자리다.
     *
     * <p>값 집합이 닫힌 어휘가 아니다 — 정규화 후에도 서른셋이고 빈 문자열이 185행,
     * {@code (*1)}·{@code (주1)} 같은 각주 기호와 서술 문장이 섞인다.
     */
    AUDIT_OPINION_ADVERSE,

    /**
     * 그 회계연도의 감사인이 전년과 다르면 1, 같으면 0. 전년을 모르면 값을 내지 않는다.
     *
     * <p>한 회계연도에 행이 둘이므로 {@code adtor}를 <b>연도별 집합으로 접어</b> 견준다 —
     * 한 해의 두 행이 다르다고 교체로 세지 않는다.
     */
    AUDITOR_CHANGED;

    /** DB 문자열에서 되돌린다. <b>모르는 값에 던지지 않는다</b> — 이유는 클래스 javadoc에 있다. */
    public static GovernanceMetric find(String key) {
        for (GovernanceMetric metric : values()) {
            if (metric.name().equals(key)) {
                return metric;
            }
        }
        return null;
    }
}
