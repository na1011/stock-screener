package com.stockscreener.indicator;

/**
 * 상대 비교 지표가 <b>무엇과 견주어</b> 나온 값인가.
 *
 * <p>모집단이 하나뿐일 때는 이 개념이 필요 없었다. 업종 축이 생기면서 같은 화면에 모집단이
 * 다른 두 조건이 함께 놓이게 됐고, 그러면 사용자가 보는 "상위 50%"의 뜻이 조건마다 달라진다 —
 * 값은 둘 다 0~1이라 <b>화면으로는 구분되지 않는다</b>(ADR-0044).
 *
 * <p>MUST NOT: 화면이 지표 코드로 이 값을 유추하지 않는다. 서버가 카탈로그로 내려주며,
 * 코드 접미사로 분기하는 순간 지표가 추가될 때마다 화면을 고쳐야 한다.
 */
public enum IndicatorPopulation {

    /**
     * 같은 지수 안. 코스피200 종목은 코스피200 안에서, 코스닥150 종목은 코스닥150 안에서
     * 매긴다(ADR-0036).
     */
    UNIVERSE,

    /**
     * 같은 업종 안. <b>지수는 가리지 않고 분류 체계는 가린다</b> — 소분류(표본이 모자라면
     * 중분류)로 묶되 KSIC와 SIC를 섞지 않는다(ADR-0044 · ADR-0092). 두 체계는 앞 2자리가
     * 실제로 겹쳐서, 섞으면 <b>에러 없이 값이 그럴듯하다.</b> 표본이 5 미만이면 값을 내지 않는다.
     */
    SECTOR
}
