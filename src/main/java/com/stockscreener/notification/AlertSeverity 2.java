package com.stockscreener.notification;

/**
 * 알림의 심각도. 채널 선택과 억제 정책의 근거가 된다.
 *
 * <p>spec §8이 "이메일과 메신저 두 채널 모두"를 요구하지만, 모든 알림을 두 채널로 보내면
 * 곧 아무도 보지 않게 된다. 심각도를 구분해두면 Phase 6이 채널별 임계를 정할 수 있다.
 */
public enum AlertSeverity {

    /** 정상 완료 통지. 기본적으로 로그에만 남긴다. */
    INFO,

    /**
     * 부분 실패. 배치가 끝나긴 했으나 일부 종목이 실패한 상태다.
     *
     * <p>일일 갱신에서 가장 흔한 심각도다. 850종목 중 두어 개가 실패하는 것은 정상 범위이며,
     * 이것을 ERROR로 올리면 매일 빨간불이 떠서 진짜 장애를 가린다.
     */
    WARNING,

    /**
     * 조치가 필요한 실패. 배치가 실패했거나 소스 스펙 변경이 의심되는 상태다.
     */
    ERROR,

    /**
     * 즉시 대응이 필요하다. 인증 실패처럼 방치하면 데이터가 계속 갱신되지 않는 상태다.
     */
    CRITICAL
}
