-- V28의 컬럼 설명이 틀렸다. 부호 규약은 회사마다 갈린다.
--
-- V28은 "유출을 양수 크기로 담는다"고 적었다. 근거가 탐침 8종목이었고 그 여덟은 실제로 전부
-- 양수였는데, 350종목 재적재에서 22행(1.5%)이 음수로 왔다 — LG화학·S-Oil·롯데쇼핑과 소형주
-- 열 곳이다. 값이 틀린 것이 아니라 표기가 다르다(LG화학 FY2023이 -12.96조인데 그 해 실제
-- 설비투자가 그 규모다). 계정이 "유형자산의 취득"이라 음수일 수 없다.
--
-- 마이그레이션을 하나 더 두는 이유는 V28이 이미 적용됐기 때문이다. 적용된 파일을 고치면
-- 체크섬이 깨져 Flyway가 기동을 막는다 — 실제로 그렇게 막혔다. 주석 한 줄이라도 같다.
--
-- 크기를 취하는 것은 지표 계층(FreeCashFlow)이 한다. 여기서 값을 정규화하지 않는 이유는
-- financial_statement가 원자료만 담기 때문이고, 미리 정규화하면 소스의 표기가 실제로 바뀌었을
-- 때 알아볼 방법이 사라진다. 실측과 경위는 ADR-0067과 dart-financial.md의
-- 「계정별 가용성」 절에 있다.
COMMENT ON COLUMN financial_statement.capex IS
    '자본적지출(유형자산의 취득, 현금흐름표 투자활동). 부호 규약이 회사마다 갈려 음수로 오는 '
    '행이 있다(실측 1.5%) — 계정이 취득이라 음수일 수 없으므로 표기이며, 크기를 취하는 것은 '
    '지표 계층의 몫이다. 잉여현금흐름 = operating_cash_flow - abs(capex). '
    '무형자산의 취득은 포함하지 않는다.';
