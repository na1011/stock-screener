-- V8: 시가총액 상위 유니버스 추가
--
-- 지수 구성종목을 주는 공식 무료 API가 없고 정확한 CSV를 영구히 구할 수 없다는 판단에서
-- 유니버스를 "시가총액 상위 N"으로 재정의했다(ADR-0012). 근거는 실측이다 — 공공데이터포털
-- 시세 API가 basDt만으로 전종목(2,872건)과 시가총액을 1콜에 주고, 과거 시점도 재현된다.
--
-- IMPORTANT — 기존 KOSPI200·KOSDAQ150·SP500 행을 지우지 않는다. 셋 다 살려두는 이유가 다르다.
--   KOSPI200·KOSDAQ150 — 정확한 구성종목을 확보할 경로가 생기면 그때 쓴다. 시드 CSV 폴백이
--                        여전히 이 코드를 담당하며, ADR-0008이 시드 구현 삭제를 금지한다.
--   SP500             — 미국은 v1.1로 연기됐을 뿐 구조는 그대로 둔다(ADR-0010).
-- universe_membership이 universe_code를 FK로 참조하므로, 지우면 그 지수의 편입 이력도 함께
-- 사라진다. 이력은 되돌릴 수 없다.
--
-- 새 코드에 지수명을 차용하지 않은 것이 이 마이그레이션의 핵심이다. 시총 상위 200은 실제
-- 코스피200과 80~90%만 겹친다(지수는 유동비율·업종 안배를 반영한다). 'KOSPI200'이라는 이름에
-- 다른 내용을 담으면 화면에 "코스피200"이라 적히는데 실제로는 아닌 상태가 되고, 그 차이는
-- 아무 에러도 내지 않으면서 사용자에게 잘못 전달된다.

-- is_active = false로 넣는다. 담당 어댑터가 @ConditionalOnApiKey라 키 없는 환경에서는
-- 등록되지 않는데, 활성으로 두면 UniverseRebalanceJob이 "소스 없음"으로 실패해
-- 배치 전체가 PARTIAL_SUCCESS가 된다. 키를 넣고 실제로 쓸 때 UPDATE로 켠다.
--
-- 반대로 하면(활성으로 넣고 나중에 끄기) 키 없는 개발·CI에서 매번 실패 알림이 쌓인다.
-- 스케줄러 기본값을 꺼둔 것과 같은 이유다 — 어댑터 없이 켜면 실패만 쌓인다.
INSERT INTO universe (code, name, market_code, is_active) VALUES
    ('KOSPI_TOP200',  '코스피 시총 상위 200',  'KOSPI',  false),
    ('KOSDAQ_TOP150', '코스닥 시총 상위 150', 'KOSDAQ', false);

-- IMPORTANT — 기존 세 유니버스를 비활성으로 내리지 <b>않는다.</b> 처음에는 그렇게 했다가
-- 되돌렸고, 그 이유를 남긴다.
--
-- 시드 유니버스를 내리면 <b>키가 없는 환경에 활성 유니버스가 하나도 남지 않는다.</b>
-- 시총 유니버스 어댑터는 @ConditionalOnApiKey라 키 없는 개발·테스트 컨텍스트에서 등록되지
-- 않기 때문이다. 그러면 UniverseRebalanceJob이 대상 0건으로 돌고, "키 없이도 파이프라인
-- 전체를 구성·검증할 수 있다"는 ADR-0008의 근거 (3)이 무너진다. 실제로 PipelineEndToEndTest
-- 7건이 이 이유로 깨졌다.
--
-- 둘을 동시에 활성으로 두어도 충돌하지 않는다. 유니버스마다 담당 소스가 다르고
-- (KOSPI200→시드 CSV, KOSPI_TOP200→시총 어댑터) DataSourceRegistry는 유니버스 코드로
-- 라우팅하므로, 같은 코드에 소스가 둘일 때만 기동에 실패한다.
--
-- 운영에서 시드 유니버스를 쓰지 않기로 하면 그때 UPDATE 한 줄로 내린다. 그 판단은 실제
-- 적재를 해보고 시총 유니버스가 기대대로 동작하는지 확인한 뒤에 하는 것이 맞다 —
-- 지금 내리면 폴백이 동작하는지 확인할 방법이 함께 사라진다.
