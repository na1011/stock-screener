-- V45: 미국 시총 상위 1,000을 조회 대상으로 연다.
--
-- V39가 is_active = false로 만들며 이유를 셋 적었다. 그 셋 중 둘이 닫혔고 하나는 확인했다.
--
--   1) 담당 어댑터가 @ConditionalOnApiKey다 — 키가 없으면 등록되지 않는다.
--      여전히 참이지만 켜기를 막지 않는다. 편입 1,000건이 이미 쌓여 있어(2026-08-31)
--      어댑터가 없어도 조회는 되고, 없으면 주간 리밸런싱만 실패로 알린다.
--   2) "편입 직후에는 시세도 지표도 없다" — 닫혔다. 2026-08-31에 180거래일 × 1,000종목의
--      지표를 백필했다(14,634,025행). 백분위·업종상대도 함께 났다.
--   3) "ADR-0072의 premise가 켜기를 명시적으로 막는다 — 활성 프리셋 여덟의 universe_code가
--      NULL이라 켜는 순간 원화 MARKET_CAP 임계가 USD 값에 걸린다" — 닫혔다. ADR-0106이
--      임계에 통화 축을 달았고, 임계가 시장을 따라간다. 값이 없는 통화는 조용히 통과하지
--      않고 실행이 거절된다.
--
-- MUST NOT: US_LISTED를 함께 켜지 않는다. US_TOP1000의 1,000종목이 전부 US_LISTED에도
-- 편입돼 있어(1,000/1,000 실측) 한 종목이 활성 유니버스 둘에 속하고, PercentileCalculator의
-- UPSERT가 같은 행을 두 번 건드려 PostgreSQL이 배치를 죽인다(ADR-0036 §규칙).
-- 그 시끄러움이 안전장치이지 결함이 아니다.
--
-- 이 UPDATE는 테스트 DB에도 걸린다. 거기서는 US_TOP1000의 편입이 0건이고,
-- MarketScope가 「전체」의 시장·통화를 편입이 있는 유니버스로만 정하므로 판정에 안 들어온다.
--
-- 되돌리는 법은 이 문장의 반대다 — UPDATE universe SET is_active = false WHERE code =
-- 'US_TOP1000'. 편입·지표·임계는 그대로 남으므로 다시 켜는 데 재적재가 필요 없다.

UPDATE universe SET is_active = true WHERE code = 'US_TOP1000';
