-- V11: 지표 값 구간의 자연어 라벨을 카탈로그에 싣는다
--
-- .claude/rules/frontend.md가 "지표를 값만 나열하지 않는다"를 MUST NOT으로 두고 있는데,
-- 정작 조건 빌더가 그 위반이었다. 사용자는 PER 입력칸에 무슨 숫자를 넣어야 하는지 알 수
-- 없었다. 경계 자체는 이미 @IndicatorMeta(interpretation)에 산문으로 있었다 —
-- "통상 70 이상이면 과매수, 30 이하면 과매도로 본다". 화면이 문장을 파싱할 수 없었을 뿐이다.
--
-- 그래서 이 컬럼은 새로운 투자 판단을 더하지 않는다. 이미 적혀 있던 경계를 구조로 옮긴다.


-- ---------------------------------------------------------------------------
-- 왜 jsonb 한 컬럼인가
--
-- V3가 조건을 jsonb로 두는 안을 기각한 근거는 "indicator FK를 잃는다"였다. 구간은 그 반대다 —
-- 다른 행을 참조하지 않고, 지표 하나에 종속되며, 언제나 그 지표와 함께 통째로 읽힌다.
-- 구간만 따로 조회할 일이 원리적으로 없다.
--
-- 정규화 테이블로 두면 IndicatorCatalog의 SELECT 하나가 일대다 조인이 되어 RowMapper가
-- 그룹핑을 해야 한다. 얻는 것 없이 읽기 경로 세 곳(activeIndicators/describe/find)이
-- 전부 복잡해진다.
--
-- 정본은 여전히 계산 클래스의 @IndicatorMeta(bands)이고 이 컬럼은 기동 시 덮어써지는
-- 사본이다. 그래서 여기 손으로 넣은 값은 다음 기동에 사라진다 — 의도된 동작이다.
-- ---------------------------------------------------------------------------
ALTER TABLE indicator ADD COLUMN bands jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN indicator.bands IS
    '값 구간별 자연어 라벨의 배열. [{"label":"매우 높음","from":20,"to":null}, …]. '
    'from은 포함, to는 미포함, null은 그쪽으로 열려 있음을 뜻한다. '
    '정본은 계산 클래스의 @IndicatorMeta(bands)이고 이 컬럼은 기동 시 갱신되는 사본이다. '
    '무차원 지표에만 채운다 — 주가 스케일 지표에 붙이면 종목마다 뜻이 달라진다.';
