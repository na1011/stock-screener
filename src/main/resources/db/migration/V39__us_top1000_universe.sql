-- V39: 미국 노출 유니버스 — 시가총액 상위 1,000
--
-- US_LISTED(8,504종목)는 「적재는 넓게」의 쪽이고, 스크리닝에 노출할 모집단이 따로 필요하다.
-- 켜면 지표 하나 없는 종목이 프리셋 결과에 실리고(ADR-0087) MAX_ROWS가 상시 발화한다.
-- 국내가 시총 상위 350/2,872(12.2%)인 것과 대칭으로 1,000/8,504(11.8%)를 고른 것은
-- 사용자 결정이다(2026-08-30).
--
-- IMPORTANT — US_LISTED를 좁혀 쓰지 않고 새 코드를 만드는 이유가 셋이다.
--   1) ADR-0086 §규칙의 「적재는 넓게, 노출은 좁게」. 좁히면 적재 대상이 함께 좁아진다.
--   2) UniverseReconciler가 첫 실행에서 거부한다 — current가 8,504라 제외 비율이 88%이고
--      MAX_REMOVAL_RATIO(0.3)를 넘는다.
--   3) 8,504 편입 원장이 그 순간 닫힌다. 지나간 시점의 유니버스는 사후 복원이 불가능하다.
-- 새 코드에서는 2가 성립하지 않는다 — reconcile의 current가 그 코드의 현재 편입이라
-- 첫 실행에서 0이고 removed도 0이다.
--
-- IMPORTANT — 코드에 N을 담는다. V8이 「지수명을 차용하지 않는다」로 금지한 것은
-- 'KOSPI200'처럼 남의 지수 이름을 빌리는 것이지 N 자체가 아니다. KOSPI_TOP200의 200도
-- 우리가 고른 값이며, 그것을 코드에 넣은 것이 국내의 의도된 선례다.
-- N을 코드에서 빼면 N이 바뀌는 날 같은 코드의 편입 원장이 두 정의를 담게 되고,
-- 어느 정의였는지 사후에 구분할 수 없다 — ADR-0086이 SP500 재사용을 기각한 그 형태다.
-- N을 넣으면 N 변경이 새 코드를 강제해 원장이 정직해진다. 대가는 이력 연속성이 끊기는
-- 것인데, 정의가 바뀌면 그것은 다른 유니버스가 맞다.
--
-- 이름이 내용과 어긋나는 자리를 함께 적어 둔다. 편입 후보는 우리 DB의
-- financial_statement.shares_outstanding으로만 만들어지므로, 재무를 파싱해 내지 못한 종목은
-- 시총이 아무리 커도 후보가 아니다 — 2026-08-31 실측으로 AMZN·JNJ·XOM·CSCO·TSM(재무 0행)과
-- V·BRK.A/B(주식수 전량 NULL)가 그 상태다. 국내에도 같은 형태의 배제가 있지만
-- (MarketCapUniverseAdapter가 시총이 '-'이거나 파싱 실패면 후보에서 뺀다) 국내는 상위권에
-- 안 걸렸고 미국은 걸린다. 여는 조건은 새 ADR의 §결과에 있다.
INSERT INTO universe (code, name, market_code, is_active) VALUES
    ('US_TOP1000', '미국 시총 상위 1,000', 'US', false);

-- is_active = false다. 이유가 V8·V34와 같고 하나 더 있다.
--   1) 담당 어댑터가 @ConditionalOnApiKey라 키 없는 환경에서 등록되지 않는다.
--   2) 편입 직후에는 시세도 지표도 없다.
--   3) ADR-0072의 premise가 켜기를 명시적으로 막는다 — 활성 프리셋 여덟의 universe_code가
--      NULL이라 켜는 순간 원화 MARKET_CAP 임계가 USD 값에 걸린다. 그 전제문이
--      "시장별 프리셋을 가르기 전에는 실행하지 않는다"이다.
--
-- MUST NOT: 이 false를 "그러니 편입해도 안전하다"로 읽지 않는다(V34가 같은 문장을 적었다).
-- 편입 행은 유니버스를 다시 내려도 남는다.
--
-- MUST NOT: US_LISTED와 함께 켜지 않는다. US_TOP1000은 그 부분집합이라 한 종목이 활성
-- 유니버스 둘에 동시에 편입되고, PercentileCalculator의 UPSERT가 같은 행을 두 번 건드려
-- PostgreSQL이 배치를 죽인다(ADR-0036 §규칙). 그 시끄러움이 안전장치이지 결함이 아니다.
