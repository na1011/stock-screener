-- V12: 워치리스트 알림을 엣지 트리거로 만들기 위한 직전 판정 상태
--
-- watchlist_item 자체는 V3에 이미 있다. 여기서 더하는 것은 컬럼 하나뿐이다.
--
-- last_notified_at만으로는 "조건이 거짓이 되었다"를 표현할 수 없다. 그 값은 "마지막으로
-- 알린 시각"이라 지난 판정이 참이었는지 거짓이었는지를 모른다. 그래서 그것만으로 만들 수 있는
-- 억제는 "N일에 한 번"뿐이고, 조건이 계속 참인 종목은 N일마다 같은 알림을 계속 보낸다.
--
-- 원하는 동작은 다르다 — 거짓에서 참으로 넘어간 그 순간에만 알린다. 그것이 사용자가
-- 알고 싶은 사건이고, 참이 유지되는 동안의 침묵이 곧 "아직 그대로다"라는 정보다.


ALTER TABLE watchlist_item ADD COLUMN last_satisfied boolean;

-- NULL은 "아직 판정한 적 없음"이고 판정 시 거짓으로 취급한다. 방금 담은 종목이 이미 조건을
-- 만족하고 있으면 첫 배치에서 알림이 가는데, 그것이 맞는 동작이다 — 사용자는 그 종목이
-- 조건에 맞는지 궁금해서 담았다.
--
-- MUST NOT: DEFAULT false를 주지 않는다. 그러면 "판정한 적 없음"과 "판정했고 거짓이었음"이
-- 같은 값이 되어, 나중에 "이 항목은 한 번도 평가되지 않았다"를 물을 수 없다.
COMMENT ON COLUMN watchlist_item.last_satisfied IS
    '직전 배치의 조건 판정 결과. NULL은 아직 판정한 적 없음이며 거짓으로 취급한다. 엣지 트리거의 근거다.';

COMMENT ON COLUMN watchlist_item.last_notified_at IS
    '마지막으로 알린 시각. 억제의 근거는 last_satisfied이고 이 값은 화면 표시용이다.';

-- 이 테이블에서 screen_id의 FK는 CASCADE도 SET NULL도 아니다(V3). 그것은 의도된 선택이며,
-- ScreenController가 그 제약 위반을 409 SCREEN_IN_USE로 옮긴다.
-- SET NULL로 바꾸면 화면을 지운 순간 워치리스트가 조용히 알림을 멈추는데, 사용자는
-- 그것을 "조건에 안 맞았나 보다"로 읽는다. 여기서 되돌리지 않는다.
