-- 거버넌스 원문 표의 열 뜻이 **소스마다 다르다**는 것을 주석에 적는다 (P28).
--
-- 표 구조는 한 자리도 안 바꾼다. 고치는 것은 COMMENT뿐이고, 그 COMMENT가 정본이라
-- 갈리면 다음 세션이 국내 계약을 미국 행에 적용한다 — 그 오독은 값이 그럴듯해서 안 드러난다.
--
-- 미국 배당(Alpaca cash_dividends)이 두 번째 소스로 들어오면서 갈린 것이 넷이다.
-- 원문의 「한 행」이 국내는 **보고서 표의 한 줄**이고 미국은 **결제 하나**다.

COMMENT ON COLUMN governance_report_row.bsns_year IS
    '그 행이 속한 보고 기간의 해. 소스마다 무엇으로 정하는지가 다르다 — DART는 **요청한 '
    '사업연도**이고(한 응답이 3개년을 열로 주므로 응답 행의 회계연도가 아니다), Alpaca 배당은 '
    '**그 결제의 ex_date가 든 역년**이다. 뒤쪽을 요청 연도로 두면 앵커를 바꿔 재적재할 때 '
    '같은 배당이 다른 키로 한 번 더 들어가 합이 부푼다.';

COMMENT ON COLUMN governance_report_row.reprt_code IS
    '그 행이 어느 보고서 계열에서 왔는가. DART는 보고서 코드(11011=사업보고서)이고, '
    '벤더에 그 개념이 없으면 **그 소스의 이름표**다(Alpaca 배당은 CASHDIV). '
    'MUST NOT: 개념이 없는 소스에 11011을 재사용하지 않는다 — 국내 보고서에서 온 행처럼 읽힌다.';

COMMENT ON COLUMN governance_report_row.receipt_no IS
    '그 행의 판을 가르는 키. DART는 소스 rcept_no(14자리)이고, 그 개념이 없는 소스는 **날짜를 '
    '8자리 숫자로** 쓴다(Alpaca 배당은 결제 행이 ex_date, 사건 0건인 해가 「연도+1231」). '
    'MUST: 숫자로 시작하게 둔다 — 정정본 선택이 이 값의 **문자열 비교**라, 문자로 시작하면 '
    '여덟 자리 날짜 전부보다 크게 앉아 **무배당 행이 실제 배당 행을 이긴다**. '
    'MUST: 데이터 없음 행에도 값을 준다(빈 문자열로 두지 않는다) — 국내용 스탬프 경로'
    '(stampNoData)와 미스탬프 집계가 둘 다 receipt_no = ''''로 대상을 잡으므로, 값을 주면 '
    '그 둘이 다른 소스의 행을 건드리지도 세지도 않는다. 다만 DART의 status 013 행은 응답에 '
    'rcept_no가 없어 **여전히 빈 문자열**이고, 그것을 같은 보고서의 형제 행이 나중에 채운다.';

COMMENT ON COLUMN governance_report_row.published_at IS
    '그 행을 **그날 알 수 있었는가**를 정하는 날짜. DART는 rcept_no 앞 8자리에서 유도한 공시일이고, '
    'Alpaca 배당은 **ex_date**다(그날 배당락이 일어나 시장이 안다). '
    'MUST NOT: 모르면 지어내지 않는다 — 폴백으로 회계연도 말일을 넣으면 없는 공시일을 만들게 되고, '
    '지표의 계단 함수가 그 날짜를 「그날 알고 있었다」로 읽는다. DART status 013 행과 '
    'Alpaca의 「그 해에 사건이 없었다」 행이 둘 다 NULL인 이유가 이것이다.';
