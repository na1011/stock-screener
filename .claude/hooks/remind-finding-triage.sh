#!/bin/bash
# PostToolUse: 작업 중 발견한 것을 어느 갈래로 보낼지 상기시킨다.
#
# 사용자가 지목한 병 — *"본 세션 작업으로 생긴 것이 아닌 원래 있던 결함이다"*라며 애써 무시하고
# 넘어가는 것. 그것이 누적되면 큰 오류가 되거나 `docs/progress.md`가 폭증한다.
#
# ## 왜 여기인가 — 트리거가 명령과 도구 호출이다
#
# `harness-core.md`의 배치표가 「명령이 트리거면 hook」이라 답한다. 그리고 **세션 시작 주입으로는
# 안 된다** — 그 자리는 0%에 한 번 뜨는데, 실측으로 **커밋은 세션당 7회·중앙값 72% 지점**에
# 난다(103세션 전수). 발견과 판단이 그 창에서 일어나므로 규칙이 가장 필요한 시점이 주입이 가장
# 희석된 시점이다. 같은 파일의 다른 규칙이 그 감쇠를 수로 적어 뒀다 — 스텝당 약 5.6%, OR 0.944.
#
# 두 자리를 잡는다.
#   - `git commit` — 판단이 **글로 착지하는** 자리다. 실측된 회피 하나가 커밋 본문에 사실을 다
#     적고도 결론을 안 냈다(*"ops/dump-db.sh는 UPDATE 전에 떴다"*).
#   - `AskUserQuestion` — 실측된 또 하나가 옵션 설명 안에서 났다(*"이 변경 이전부터 있는 별개의
#     결함이므로 범위를 넓히지 않고…"*).
#
# ## MUST NOT: 세션당 1회로 억제하지 않는다
#
# 다른 알림 훅들과 다른 점이 이것이다. 저쪽은 **같은 사실을 두 번 말하지 않으려고** 억제하는데,
# 여기서 값을 만드는 것은 **반복 그 자체**다 — 한 번만 뜨면 지금 고치려는 그 희석으로 돌아간다.
# 대가는 세션당 약 7줄이고, 그것이 이 훅의 설계 비용이다.
#
# ## 정본은 여기다
#
# 이 문장의 사본을 다른 곳에 두지 않는다. `docs/progress.md` 머리말과
# `remind-verify-options.sh`에 같은 문장을 뒀다가 걷었다 — 자리가 셋이면 거울 등록이 따라붙고,
# 그 거울은 갈림을 못 잡으면서 유지 비용만 만든다. **인라인한 이 자리가 정본이다**(`harness-core.md`).
#
# jq가 없으면 조용히 통과한다. 부재 경보는 `check-doc-staleness.sh`가 세션 시작에 한 번 낸다.
set -euo pipefail

command -v jq >/dev/null 2>&1 || exit 0

input=$(cat)
tool=$(echo "$input" | jq -r '.tool_name // empty')
[ -z "$tool" ] && exit 0

case "$tool" in
  AskUserQuestion) ;;
  Bash)
    cmd=$(echo "$input" | jq -r '.tool_input.command // empty')
    # `git commit`만 본다. 커밋을 **언급만** 하는 명령(문서·grep)도 걸리지만 그것은 오탐이
    # 아니라 값이다 — 그 자리에서도 갈래를 물어야 한다. 대신 `git log --grep`처럼 읽기만 하는
    # 것까지 무는 것은 예산 낭비라, 실제로 커밋을 만드는 형태로 좁힌다.
    echo "$cmd" | grep -qE '(^|[[:space:];|&])git[[:space:]]+commit([[:space:]]|$)' || exit 0
    ;;
  *) exit 0 ;;
esac

jq -n --arg ctx "**발견한 것을 갈래로 보냈는가.** 현재 작업과 **큰 틀에서 같이 묶여 있으면 이번에 처리하고, 아니면 넘긴다**(\`docs/progress.md\`). 재보니 결함이 아니면 **그 세 답**(무엇이 읽는가 · 무엇이 틀리는가 · 지금 닿는가)을 함께 적는다 — **안 재고 넘기는 것만이 무시다.** **「내가 만든 것인가」는 갈래를 정하지 않는다** — 정하는 것은 관계와 파급이다. 넘길 판단이 서면 그 판단을 사용자에게 보고한다." \
  '{
    hookSpecificOutput: {
      hookEventName: "PostToolUse",
      additionalContext: $ctx
    }
  }'
exit 0
